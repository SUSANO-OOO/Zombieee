import {buildRigidJointAtlas} from './build-v177-rigid-joint-atlas.mjs';
import {writeFile}from'node:fs/promises';import sharp from'sharp';
const revision=process.argv[2]??'r3';
if(!['r2','r3'].includes(revision))throw Error('Unknown Omega revision');
let atlas;
const result=await buildRigidJointAtlas({
 sourceDirectory:'assets/source/v100/joints/takuya-omega-'+revision,
 assetPath:'/art/v100/joints/takuya-omega-'+revision+'.webp',
 dataFile:null,captureAtlas:value=>{atlas=value;},exportName:'V104_OMEGA_JOINT_ATLASES',
 generator:'scripts/build-v104-omega-right-joints.mjs',
 description:'Blender5.2 fixed-length original Omega body with dedicated closed giant RIGHT hand gripping a broader greatsword. Empty smaller LEFT hand, source-bound boot support, unchanged face/costume/body pixels. No anatomical scaling. Authored native proof and normal-play acceptance tracked separately.',
});
const {data,info}=await sharp('public'+atlas.path).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const part=atlas.parts.find(p=>p.bone===atlas.weaponBone),s=part.source,d=part.destination,points=[];
for(let x=0;x<s.w;x++){
 let top=s.h,bottom=-1;
 for(let y=0;y<s.h;y++)if(data[((s.y+y)*info.width+s.x+x)*4+3]>=8){top=Math.min(top,y);bottom=Math.max(bottom,y);}
 if(bottom>=0)for(const [u,v]of[[x,top],[x+1,top],[x,bottom+1],[x+1,bottom+1]])points.push([d.x+u*d.w/s.w,d.y+v*d.h/s.h]);
}
const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
const cross=(o,a,b)=>(a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0]),lo=[],hi=[];
for(const p of sorted){while(lo.length>1&&cross(lo.at(-2),lo.at(-1),p)<=0)lo.pop();lo.push(p);}
for(const p of sorted.toReversed()){while(hi.length>1&&cross(hi.at(-2),hi.at(-1),p)<=0)hi.pop();hi.push(p);}
atlas.weaponHull=lo.slice(0,-1).concat(hi.slice(0,-1));atlas.weaponFloorY=494;
await writeFile('app/v104OmegaJointData.js','// Generated by scripts/build-v104-omega-right-joints.mjs; original body and fixed-length Blender rig.\nexport const V104_OMEGA_JOINT_ATLASES='+JSON.stringify({'takuya-omega':atlas})+';\n');
console.log(JSON.stringify({...result,weaponHullPoints:atlas.weaponHull.length}));
