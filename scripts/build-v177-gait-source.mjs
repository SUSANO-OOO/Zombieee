import assert from 'node:assert/strict';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { V177_JOINT_ATLASES } from '../app/v177JointPresentation.js';

// Preserve the authored gait metadata without repacking or changing source
// pixels and Blender matrices. Match the anatomy actually used by runtime.
export async function authoredGaits() {
  const candidates = [];
  for (const relative of await readdir('assets/source', { recursive: true })) {
    if (!relative.replaceAll('\\', '/').endsWith('/parts.json')) continue;
    const file = 'assets/source/' + relative.replaceAll('\\', '/');
    const bytes = await readFile(file), source = JSON.parse(bytes);
    if (source.legConstraints?.length !== 2) continue;
    candidates.push({ file, source, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  const result = {};
  for (const [kind, atlas] of Object.entries(V177_JOINT_ATLASES)) {
    if (atlas.type !== 'rigid-parts' || atlas.legConstraints?.length !== 2) continue;
    let matches = candidates.filter(({ source }) =>
      JSON.stringify(source.legConstraints) === JSON.stringify(atlas.legConstraints)
      && Math.abs(source.motion.walk.spanPx / source.motion.walk.stanceFraction - atlas.cycleDistance) < 1e-6);
    const named = matches.filter(({ source }) => source.kind === kind);
    if (named.length) matches = named;
    assert.ok(matches.length, `No matching authored anatomy for ${kind}`);
    const values = matches.map(({ source }) => ({ stanceFraction: source.motion.walk.stanceFraction,
      offsets: Object.fromEntries(source.legConstraints.map((leg, index) => [leg.effectorBone, source.rig.legs[index].offset])) }));
    for (const value of values) assert.deepEqual(value, values[0], `Ambiguous gait for ${kind}`);
    assert.ok(values[0].stanceFraction > 0 && values[0].stanceFraction < 1);
    assert.ok(Object.values(values[0].offsets).every(Number.isFinite));
    result[kind] = { ...values[0], sources: matches.map(({ file, sha256 }) => ({ file, sha256 })) };
  }
  return result;
}

const output = '// Generated by scripts/build-v177-gait-source.mjs from matching authored anatomy.\n'
  + 'export const V177_AUTHORED_GAITS = ' + JSON.stringify(await authoredGaits(), null, 2) + ';\n';
if (process.argv.includes('--check')) assert.equal(await readFile('app/v177GaitSourceData.js', 'utf8'), output);
else await writeFile('app/v177GaitSourceData.js', output);
