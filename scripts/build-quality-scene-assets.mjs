import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const check=process.argv.includes('--check');
const folder='assets/source/quality-20261028/scenes/';
const plan=JSON.parse(await readFile(folder+'scene-sources-r1.json','utf8'));
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
async function save(file,bytes){
 if(check)assert.deepEqual(await readFile(file),bytes,file);
 else{await mkdir(path.dirname(file),{recursive:true});await writeFile(file,bytes);}
}
for(const model of plan.models){
 assert.ok(model.source.startsWith('assets/source/quality-20261028/identity/')&&!model.source.includes('..'));
 assert.equal(sha(await readFile(model.source)),model.sha256,'Locked character model changed: '+model.id);
}
const records=[],runtime={};
for(const scene of plan.scenes){
 assert.ok(/^[a-z0-9-]+$/u.test(scene.id)&&scene.alt);
 assert.ok(scene.master.startsWith(folder)&&!scene.master.includes('..'));
 assert.ok(scene.path.startsWith('/art/v100/quality-20261028/scenes/')&&scene.path.endsWith('.webp'));
 assert.equal(runtime[scene.id],undefined,'Duplicate scene ID');
 const master=await readFile(scene.master);
 assert.equal(sha(master),scene.masterSha256,'Scene source changed: '+scene.id);
 let previous=null;
 if(scene.previousPath){
  const original=await readFile('public'+scene.previousPath);
  assert.equal(sha(original),scene.previousSha256,'Historical source changed: '+scene.id);
  previous={path:scene.previousPath,sha256:sha(original),bytes:original.length};
 }
 const [width,height]=scene.dimensions;
 assert.ok(Number.isInteger(width)&&Number.isInteger(height)&&width>0&&height>0);
 const bytes=await sharp(master).resize(width,height,{fit:'cover'}).webp({quality:94,effort:6}).toBuffer();
 await save('public'+scene.path,bytes);
 runtime[scene.id]={path:scene.path,previousPath:scene.previousPath??null,alt:scene.alt,newEvent:scene.newEvent===true,...(scene.detail?{detail:scene.detail}:{})};
 records.push({...scene,previous,bytes:bytes.length,sha256:sha(bytes),sourceRights:plan.sourceRights,producerApproval:plan.producerApproval});
}
const source='// Generated by scripts/build-quality-scene-assets.mjs. Historical masters remain preserved.\n'
 +'export const V100_QUALITY_SCENE_ASSETS=Object.freeze('+JSON.stringify(runtime,null,2)+');\n'
 +'const byPrevious=new Map(Object.values(V100_QUALITY_SCENE_ASSETS).filter(row=>row.previousPath).map(row=>[row.previousPath,row.path]));\n'
 +'export const v100QualityScenePathFor=path=>byPrevious.get(path)??path;\n';
await save('app/v100QualitySceneAssets.js',Buffer.from(source));
const reusedScenes=plan.reusedScenes??[];
for(const scene of reusedScenes){
 assert.ok(scene.reason&&scene.modelIds.length&&scene.modelIds.every(id=>plan.models.some(model=>model.id===id)),'Reuse must name its reviewed models');
 assert.ok(!records.some(row=>row.id===scene.id||row.path===scene.path),'Reused scene cannot also be a replacement');
 const bytes=await readFile('public'+scene.path),meta=await sharp(bytes).metadata();
 assert.equal(sha(bytes),scene.sha256,'Reviewed retained image changed: '+scene.id);
 assert.equal(bytes.length,scene.bytes);assert.deepEqual([meta.width,meta.height],scene.dimensions);
}
await save(folder+'runtime-provenance-r1.json',Buffer.from(JSON.stringify({generator:'scripts/build-quality-scene-assets.mjs',models:plan.models,records,reusedScenes,scope:'Model-based scene candidate. Visual review and in-game proof are separate; no likeness percentage or whole-product acceptance is claimed.'},null,2)+'\n'));
console.log(JSON.stringify({check,count:records.length,reused:reusedScenes.length,newEvents:records.filter(row=>row.newEvent).length,bytes:records.reduce((n,row)=>n+row.bytes,0)}));
