import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync, readFileSync, writeFileSync} from 'node:fs';
import ffmpeg from '@ffmpeg-installer/ffmpeg';

const rate = 44100;
const source = {
  rifle: 'assets/source/weapon-recordings/D_32P.wav',
  latch: 'assets/source/v100/audio/kenney-rpg/metalLatch.ogg',
  cloth: 'assets/source/v100/audio/kenney-rpg/cloth4.ogg',
  soft: 'assets/source/v100/audio/kenney-impact/impactSoft_heavy_000.ogg',
  wood: 'assets/source/v100/audio/kenney-impact/impactWood_heavy_000.ogg',
  steel: 'assets/source/v100/audio/kenney-impact/impactMetal_heavy_000.ogg',
  tick: 'assets/source/v100/audio/kenney-impact/impactMetal_light_000.ogg',
};
const renderDir = 'public/audio/quality-20261127/manual-strikes';
const provenanceDir = 'assets/source/quality-20261127/manual-strikes';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const ff = (args,input) => execFileSync(ffmpeg.path,['-v','error','-nostdin',...args],{input,windowsHide:true});

// Each layer keeps the original pitch. Delayed, band-limited copies of the
// rifle's own tail simulate room reflections without introducing another shot.
function layer(sourceKey, start, length, delay, gain, low, high) {
  return {sourceKey, start, length, delay, gain, low, high};
}
const recipes = [
  {cue:'ability-ranger-precision-shot', duration:.63, onsetDb:-11.5, layers:[
    layer('rifle',5.640,.55,0,1,70,10300),
    layer('rifle',5.644,.24,.056,.34,170,2600),
    layer('rifle',5.646,.25,.122,.18,250,1650),
    layer('latch',.005,.12,.205,.17,1050,5700),
  ]},
  {cue:'ability-ranger-precision-impact', duration:.24, onsetDb:-21, layers:[
    layer('soft',0,.16,0,.92,180,2100),
    layer('wood',.004,.14,.005,.70,650,5000),
    layer('tick',.002,.12,.022,.22,2400,7600),
  ]},
  {cue:'ability-scout-intercept-impact', duration:.39, onsetDb:-10.5, layers:[
    layer('soft',0,.23,0,1.15,75,1350),
    layer('steel',0,.18,.004,.94,470,6500),
    layer('cloth',.008,.16,.028,.34,550,4600),
    layer('steel',.027,.15,.069,.32,400,2900),
  ]},
];
mkdirSync(renderDir,{recursive:true});
mkdirSync(provenanceDir,{recursive:true});
const files = {};
for (const {cue, duration, onsetDb, layers} of recipes) {
  const mix = new Float32Array(Math.round(duration*rate));
  for (const part of layers) {
    const fade = Math.min(.085,part.length*.52);
    const filter = `highpass=f=${part.low},lowpass=f=${part.high},afade=t=out:st=${part.length-fade}:d=${fade}`;
    const bytes = ff(['-ss',String(part.start),'-i',source[part.sourceKey],'-t',String(part.length),
      '-af',filter,'-ar',String(rate),'-ac','1','-f','f32le','pipe:1']);
    const offset = Math.round(part.delay*rate);
    for (let i=0;i<bytes.length/4 && offset+i<mix.length;i++) mix[offset+i] += bytes.readFloatLE(i*4)*part.gain;
  }
  const onset = mix.subarray(0,Math.round(rate*.1));
  const rms = Math.sqrt(onset.reduce((sum,v)=>sum+v*v,0)/onset.length);
  if (!(rms>0)) throw Error('Silent strike '+cue);
  const gain = 10**(onsetDb/20)/rms;
  for (let i=0;i<mix.length;i++) {
    const envelope = Math.min(1,i/(rate*.001),(mix.length-1-i)/(rate*.025));
    mix[i] = envelope*.93*Math.tanh(mix[i]*gain/.93);
  }
  const path = renderDir+'/'+cue+'.mp3';
  ff(['-y','-f','f32le','-ar',String(rate),'-ac','1','-i','pipe:0','-map_metadata','-1',
    '-c:a','libmp3lame','-b:a','128k',path],Buffer.from(mix.buffer));
  files[cue] = {path:'/'+path.slice('public/'.length),hash:'sha256-'+hash(readFileSync(path))};
}
const originals = Object.values(source).map(file=>({file,sha256:hash(readFileSync(file))}));
const provenance = {license:'CC0-1.0',creators:['Ben Jaszczak','Brian Nelson','Kevin Heras','Matthew Nanney','Kenney'],
  notices:['assets/source/weapon-recordings/LICENSE.txt','assets/source/v100/audio/kenney-impact/License.txt','assets/source/v100/audio/kenney-rpg/License.txt'],
  recipe:'scripts/build-manual-strikes.mjs',originals,recipes,files};
writeFileSync(provenanceDir+'/provenance.json',JSON.stringify(provenance,null,2)+'\n');
writeFileSync('app/pwaManualStrikeFiles.js','// Generated by scripts/build-manual-strikes.mjs.\nexport const PWA_MANUAL_STRIKE_FILES = Object.freeze('+JSON.stringify(files,null,2)+');\n');
