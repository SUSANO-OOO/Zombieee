// Read-only source analysis: no pixels or identity assets are generated here.
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { spriteFrameFor } from '../app/spriteManifest.js';

export const FALLING_DEATH_KINDS = Object.freeze(['takuya', 'mugarian-president-mutated', 'takuya-omega']);
const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
function hull(points) {
  const sorted = [...new Map(points.map(p => [p.join(','), p])).values()].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const lower = [], upper = [];
  for (const p of sorted) { while (lower.length > 1 && cross(lower.at(-2), lower.at(-1), p) <= 0) lower.pop(); lower.push(p); }
  for (const p of sorted.toReversed()) { while (upper.length > 1 && cross(upper.at(-2), upper.at(-1), p) <= 0) upper.pop(); upper.push(p); }
  return lower.slice(0, -1).concat(upper.slice(0, -1));
}

export async function buildCorpsePoseData() {
  const records = [];
  for (const kind of FALLING_DEATH_KINDS) for (const direction of ['right', 'left']) {
    const frame = spriteFrameFor(kind, 'death', direction), r = frame.sourceRect;
    const source = await fs.readFile(path.resolve('public' + frame.path));
    const { data, info } = await sharp(source).extract({ left: r.x, top: r.y, width: r.w, height: r.h }).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const slices = frame.drawSlices ?? [{ x: 0, y: 0, w: r.w, h: r.h }], points = [];
    for (let x = 0; x < info.width; x++) {
      let top = info.height, bottom = -1;
      for (let y = 0; y < info.height; y++) if (data[(y * info.width + x) * 4 + 3] >= 8
        && slices.some(s => x >= s.x && x < s.x + s.w && y >= s.y && y < s.y + s.h)) {
        top = Math.min(top, y); bottom = Math.max(bottom, y);
      }
      if (bottom >= 0) points.push([x, top], [x + 1, top], [x, bottom + 1], [x + 1, bottom + 1]);
    }
    const outline = hull(points);
    if (outline.length < 3) throw new Error('Missing visible death silhouette: ' + kind);
    records.push({ kind, direction, path: frame.path, sourceRect: { ...r }, frameFlipX: frame.flipX,
      sourceSha256: createHash('sha256').update(source).digest('hex'), drawSlices: slices.map(s => ({ ...s })), alphaThreshold: 8,
      fallAngleRadians: Math.PI / 2, hull: outline });
  }
  return '// Generated by scripts/build-v102-corpse-pose-data.mjs; exact source-alpha support for falling death keys.\n'
    + 'export const V102_FALLING_DEATH_FRAMES = Object.freeze(' + JSON.stringify(records)
    + '.map(frame => Object.freeze({...frame, sourceRect:Object.freeze(frame.sourceRect), drawSlices:Object.freeze(frame.drawSlices.map(Object.freeze)), hull:Object.freeze(frame.hull.map(Object.freeze))})));\n';
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const index = process.argv.indexOf('--out');
  if (index < 0 || !process.argv[index + 1]) throw new Error('Pass an explicit --out destination');
  await fs.writeFile(path.resolve(process.argv[index + 1]), await buildCorpsePoseData());
}
