import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdirSync,readFileSync,writeFileSync} from 'node:fs';
import ffmpeg from '@ffmpeg-installer/ffmpeg';

const rate = 44100;
const source = {
  discharge: 'assets/source/weapon-recordings/D_32P.wav',
  explosion: 'assets/source/v100/audio/opengameart/chunky-explosion.mp3',
  metal: 'assets/source/v100/audio/kenney-impact/impactMetal_medium_000.ogg',
  wood: 'assets/source/v100/audio/kenney-impact/impactWood_heavy_000.ogg',
};
const output = 'public/audio/quality-20261127/chiha';
const master = 'assets/source/quality-20261127/chiha-salvo';
const hash = file => createHash('sha256').update(readFileSync(file)).digest('hex');
function ff(args,input) {
  return execFileSync(ffmpeg.path,['-v','error','-nostdin','-threads','1',...args],{input,windowsHide:true});
}
function layer(key,start,length,low,high,volume,delay=0) {
  return {key,start,length,low,high,volume,delay};
}
const takes = [
  // Short, weighty discharges leave room for each landing 180 ms later.
  {name:'launch-a', seconds:.20, peak:.92, layers:[
    layer('discharge',.699,.19,90,3800,1), layer('wood',0,.13,68,1000,.45),
    layer('explosion',.060,.15,110,780,.57),
    layer('metal',0,.08,1400,6400,.12,.012)]},
  {name:'launch-b', seconds:.20, peak:.92, layers:[
    layer('discharge',5.644,.19,90,4200,1), layer('wood',.003,.14,72,1100,.42),
    layer('explosion',.073,.14,110,810,.54),
    layer('metal',.002,.08,1500,6700,.10,.016)]},
  {name:'impact', seconds:.24, peak:.71, layers:[
    layer('wood',0,.16,100,3300,.48), layer('explosion',.051,.22,90,5100,.95),
    layer('metal',.009,.10,1400,6200,.15,.045)]},
  {name:'final', seconds:.78, peak:.75, layers:[
    layer('wood',0,.24,85,3200,.57), layer('explosion',.049,.74,62,7200,1),
    layer('metal',0,.19,1050,5800,.26,.084), layer('wood',.004,.20,100,2200,.29,.185),
    layer('metal',.006,.14,1800,5900,.10,.278)]},
];
mkdirSync(output,{recursive:true});
mkdirSync(master,{recursive:true});
const metadata={},files={};
for (const take of takes) {
  const pcm=new Float32Array(Math.round(take.seconds*rate));
  for (const part of take.layers) {
    const envelope=Math.min(part.length*.52,.30);
    const filter='highpass=f='+part.low+',lowpass=f='+part.high+',afade=t=out:st='+(part.length-envelope)+':d='+envelope;
    const bytes=ff(['-ss',String(part.start),'-i',source[part.key],'-t',String(part.length),'-af',filter,
      '-ac','1','-ar',String(rate),'-f','f32le','pipe:1']);
    const start=Math.round(part.delay*rate);
    for(let i=0;i<bytes.length/4&&i+start<pcm.length;i++) pcm[i+start]+=bytes.readFloatLE(i*4)*part.volume;
  }
  const peak=pcm.reduce((v,x)=>Math.max(v,Math.abs(x)),0);
  if(!(peak>0))throw Error('Empty mix '+take.name);
  for(let i=0;i<pcm.length;i++){
    const fade=Math.min(1,i/(rate*.001),(pcm.length-1-i)/(rate*.018));
    pcm[i]=take.peak*fade*Math.tanh(1.9*pcm[i]/peak)/Math.tanh(1.9);
  }
  const id='chiha-salvo-'+take.name,file=output+'/'+id+'.mp3';
  ff(['-y','-f','f32le','-ar',String(rate),'-ac','1','-i','pipe:0','-map_metadata','-1',
    '-c:a','libmp3lame','-b:a','128k',file],Buffer.from(pcm.buffer));
  metadata[id]={path:'/'+file.slice('public/'.length),hash:'sha256-'+hash(file)};
  files[id]={...metadata[id],bytes:readFileSync(file).length,seconds:take.seconds,layers:take.layers};
}
const total=Object.values(files).reduce((sum,f)=>sum+f.bytes,0);
const notes={creators:['Ben Jaszczak','Brian Nelson','Kevin Heras','Matthew Nanney','Joth','Kenney'],
  license:'CC0-1.0',commercialUse:true,modification:true,redistribution:true,
  producerApproval:'Issue 177, smartphone weapon and manual ability sound design using the existing licensed library.',
  references:['assets/source/weapon-recordings/provenance.json','assets/source/v100/audio/sound-design-provenance.json'],
  recipe:'scripts/build-chiha-salvo-audio.mjs',originals:Object.entries(source).map(([key,path])=>({key,path,sha256:hash(path)})),
  runtimeAssetCount:takes.length,logicalBytes:total,distinctBytes:total,files};
writeFileSync(master+'/provenance.json',JSON.stringify(notes,null,2)+'\n');
writeFileSync('app/pwaChihaSalvoFiles.js','// Generated by scripts/build-chiha-salvo-audio.mjs. Install metadata only.\nexport const PWA_CHIHA_SALVO_FILES = Object.freeze('+JSON.stringify(metadata,null,2)+');\n');
console.log(JSON.stringify({takes:takes.length,bytes:total}));
