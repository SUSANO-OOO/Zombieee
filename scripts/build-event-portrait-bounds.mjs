import { writeFile } from 'node:fs/promises';
import sharp from 'sharp';
import { EVENT_PORTRAIT_PROFILES } from '../app/visualProfiles.js';

const bounds = {};
for (const profile of Object.values(EVENT_PORTRAIT_PROFILES)) {
  const { data, info } = await sharp(`public${profile.path}`).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let bottom = -1;
  for (let y = info.height - 1; y >= 0 && bottom < 0; y--) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] >= 32) { bottom = y; break; }
    }
  }
  if (bottom < 0) throw new Error(`Empty portrait: ${profile.path}`);
  bounds[profile.path] = (bottom + 1) / info.height;
}
await writeFile('app/eventPortraitInkBounds.js', `// Generated by scripts/build-event-portrait-bounds.mjs; visible alpha >= 32.\nexport const EVENT_PORTRAIT_INK_BOTTOM = Object.freeze(${JSON.stringify(bounds, null, 2)});\n`);
