import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import sharp from 'sharp';
import { V177_JOINT_ATLASES } from '../app/v177JointPresentation.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
function convexHull(points) {
  const cross=(o,a,b)=>(a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0]);
  const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  const lower=[],upper=[];
  for(const p of sorted){while(lower.length>1&&cross(lower.at(-2),lower.at(-1),p)<=0)lower.pop();lower.push(p);}
  for(const p of sorted.toReversed()){while(upper.length>1&&cross(upper.at(-2),upper.at(-1),p)<=0)upper.pop();upper.push(p);}
  return lower.slice(0,-1).concat(upper.slice(0,-1));
}

export async function buildV177WalkerFloor() {
  const atlas=V177_JOINT_ATLASES.walker;
  assert.equal(atlas,V177_JOINT_ATLASES.turned);
  const atlasBytes=fs.readFileSync(path.join(root,'public',atlas.path));
  const {data:rgba,info}=await sharp(atlasBytes).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const sourcePath='assets/source/v100/joints/walker-r1/parts.json';
  const source=JSON.parse(fs.readFileSync(path.join(root,sourcePath),'utf8'));
  const outlines=atlas.parts.map(part=>{
    const s=part.source,d=part.destination,points=[];
    // Include every painted texel, including alpha=1 fringes, with its full
    // pixel footprint. Thresholding at 8 previously hid floor penetration.
    for(let x=0;x<s.w;x++) {
      let top=s.h,bottom=-1;
      for(let y=0;y<s.h;y++)if(rgba[((s.y+y)*info.width+s.x+x)*4+3]>=1){top=Math.min(top,y);bottom=Math.max(bottom,y);}
      if(bottom>=0)for(const [px,py]of [[x,top],[x+1,top],[x,bottom+1],[x+1,bottom+1]])
        points.push([d.x+px*d.w/s.w,d.y+py*d.h/s.h]);
    }
    assert.ok(points.length,`Empty original part: ${part.name}`);
    return {name:part.name,bone:part.bone,upper:part.upper,hull:convexHull(points)};
  });
  const data={atlasPath:atlas.path,atlasSha256:sha(atlasBytes),alphaThreshold:1,
    sourcePath,sourceLayoutSha256:sha(JSON.stringify(source)),
    partsLayoutSha256:sha(JSON.stringify(atlas.parts)),
    waist:source.rig.spine[0],neck:source.rig.head[0],
    supportParts:['far-boot','near-boot'],outlines};
  return '// Generated by scripts/build-v177-walker-floor.mjs; original identity RGBA is unchanged.\n'
    +'export const V177_WALKER_FLOOR_DATA = '+JSON.stringify(data)+';\n';
}

if(process.argv[1]&&import.meta.url===pathToFileURL(path.resolve(process.argv[1])).href) {
  const output=path.join(root,'app/v177WalkerFloorData.js'),content=await buildV177WalkerFloor();
  if(process.argv.includes('--check'))assert.equal(fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n'),content);
  else fs.writeFileSync(output,content);
  console.log(JSON.stringify({output:path.relative(root,output),check:process.argv.includes('--check'),bytes:Buffer.byteLength(content)}));
}
