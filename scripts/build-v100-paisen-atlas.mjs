import crypto from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCE_PATH = path.join(ROOT, "public/art/v060/characters/legacy/brawler-battle-gutter-v1.png");
const IDENTITY_PATH = path.join(ROOT, "public/art/v060/characters/portraits/brawler-portrait-v2.webp");
const OUTPUT_PATH = path.join(ROOT, "public/art/v100/characters/paisen-battle-v1.png");
const PROVENANCE_PATH = path.join(ROOT, "assets/source/v100/runtime/paisen-battle-atlas-provenance.json");

const CELL_WIDTH = 394;
const CELL_HEIGHT = 757;
const SOURCE_CELL_COUNT = 6;
const STATES = Object.freeze(["idle", "walk-a", "walk-b", "attack-a", "attack-b", "hit", "death"]);
const DIRECTIONS = Object.freeze(["right", "left"]);
const GENERATOR_VERSION = "v100-paisen-atlas-r1";

async function sha256(filePath) {
  const digest = crypto.createHash("sha256");
  digest.update(await fs.readFile(filePath));
  return digest.digest("hex").toUpperCase();
}

function transparentCanvas(width, height) {
  return sharp({
    create: {
      width,
      height,
      channels: 4,
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    },
  });
}

async function sourceCell(index) {
  if (!Number.isInteger(index) || index < 0 || index >= SOURCE_CELL_COUNT) {
    throw new Error(`Invalid Paisen source cell index: ${index}`);
  }
  return sharp(SOURCE_PATH)
    .extract({ left: index * CELL_WIDTH, top: 0, width: CELL_WIDTH, height: CELL_HEIGHT })
    .png()
    .toBuffer();
}

async function deriveDeathFrame(hitFrame) {
  // The approved legacy sheet contains six authored cells and its last cell is
  // the impact pose.  V1 requires a separate death state, so derive one
  // deterministically from that same Paisen identity: rotate the trimmed
  // impact pose into a grounded fall and keep the audited transparent gutter.
  const trimmed = await sharp(hitFrame).trim().png().toBuffer();
  const rotated = await sharp(trimmed)
    .rotate(90, { background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .resize({ width: CELL_WIDTH - 44, height: 300, fit: "inside", withoutEnlargement: false })
    .png()
    .toBuffer();
  const metadata = await sharp(rotated).metadata();
  const left = Math.floor((CELL_WIDTH - metadata.width) / 2);
  const top = CELL_HEIGHT - 16 - metadata.height;
  return transparentCanvas(CELL_WIDTH, CELL_HEIGHT)
    .composite([{ input: rotated, left, top }])
    .png()
    .toBuffer();
}

async function mirror(frame) {
  return sharp(frame).flop().png().toBuffer();
}

async function main() {
  const [sourceHash, identityHash] = await Promise.all([sha256(SOURCE_PATH), sha256(IDENTITY_PATH)]);
  const authoredFrames = await Promise.all(Array.from({ length: SOURCE_CELL_COUNT }, (_, index) => sourceCell(index)));
  const deathFrame = await deriveDeathFrame(authoredFrames[5]);
  const rightFrames = [...authoredFrames, deathFrame];
  const leftFrames = await Promise.all(rightFrames.map((frame) => mirror(frame)));

  const composites = [];
  for (const [row, frames] of [[0, rightFrames], [1, leftFrames]]) {
    for (const [column, frame] of frames.entries()) {
      composites.push({ input: frame, left: column * CELL_WIDTH, top: row * CELL_HEIGHT });
    }
  }
  const atlas = await transparentCanvas(CELL_WIDTH * STATES.length, CELL_HEIGHT * DIRECTIONS.length)
    .composite(composites)
    .png({ compressionLevel: 9, adaptiveFiltering: false })
    .toBuffer();
  await fs.writeFile(OUTPUT_PATH, atlas);

  const outputHash = crypto.createHash("sha256").update(atlas).digest("hex").toUpperCase();
  const provenance = {
    generator: GENERATOR_VERSION,
    sourcePolicy: "Paisen-only runtime derivative; no other playable atlas is generated by this script",
    identitySource: {
      path: "/art/v060/characters/portraits/brawler-portrait-v2.webp",
      sha256: identityHash,
    },
    sourceBattleDerivative: {
      path: "/art/v060/characters/legacy/brawler-battle-gutter-v1.png",
      sha256: sourceHash,
      width: CELL_WIDTH * SOURCE_CELL_COUNT,
      height: CELL_HEIGHT,
      cellWidth: CELL_WIDTH,
      cellHeight: CELL_HEIGHT,
      authoredCellCount: SOURCE_CELL_COUNT,
    },
    output: {
      path: "/art/v100/characters/paisen-battle-v1.png",
      sha256: outputHash,
      width: CELL_WIDTH * STATES.length,
      height: CELL_HEIGHT * DIRECTIONS.length,
      layout: "seven-horizontal-by-two-directions",
      cellWidth: CELL_WIDTH,
      cellHeight: CELL_HEIGHT,
      states: STATES,
      directions: DIRECTIONS,
    },
    stateDerivation: {
      idle: { sourceCell: 0, operation: "copy" },
      "walk-a": { sourceCell: 1, operation: "copy" },
      "walk-b": { sourceCell: 2, operation: "copy" },
      "attack-a": { sourceCell: 3, operation: "copy" },
      "attack-b": { sourceCell: 4, operation: "copy" },
      hit: { sourceCell: 5, operation: "copy" },
      death: { sourceCell: 5, operation: "trim-rotate-90-resize-grounded" },
    },
  };
  await fs.writeFile(PROVENANCE_PATH, `${JSON.stringify(provenance, null, 2)}\n`, "utf8");
  console.log(JSON.stringify(provenance, null, 2));
}

await main();
