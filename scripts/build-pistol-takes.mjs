import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import ffmpeg from '@ffmpeg-installer/ffmpeg';

const raw = 'assets/source/weapon-recordings/X_39P.wav';
const latch = 'assets/source/v100/audio/kenney-rpg/metalLatch.ogg';
const sourceDir = 'assets/source/quality-20261127/pistol-takes';
const publicDir = 'public/audio/quality-20261127/firearms';
const rate = 44100;
const duration = .42;
const hash = file => createHash('sha256').update(readFileSync(file)).digest('hex');
const presets = [
  { cue:'v104-handgun', name:'handgun', attack:[140,9000], body:[72,680], tail:[600,4800], latchGain:.035, peak:.92 },
  { cue:'weapon-suppressed-pistol', name:'suppressed-pistol', attack:[125,2600], body:[75,480], tail:[430,1650], latchGain:.085, peak:.76 },
];
const recordings = [{name:'02', start:6.441, latchDelay:24}, {name:'03', start:10.657, latchDelay:19}];
function run(args, input) {
  return execFileSync(ffmpeg.path, ['-v','error','-nostdin','-threads','1',...args], {input, windowsHide:true});
}
function samples(args) {
  const bytes = run([...args,'-ar',String(rate),'-ac','1','-f','f32le','pipe:1']);
  return new Float32Array(bytes.buffer, bytes.byteOffset, bytes.byteLength / 4);
}
function attackRms(pcm) {
  const onset = pcm.subarray(0, Math.round(rate * .2));
  return Math.sqrt(onset.reduce((sum,sample)=>sum+sample*sample,0)/onset.length);
}
function band([lo,hi]) { return 'highpass=f='+lo+',lowpass=f='+hi; }
mkdirSync(publicDir,{recursive:true});
mkdirSync(sourceDir,{recursive:true});
const files = {};
for (const preset of presets) {
  const target = attackRms(samples(['-i','public/audio/quality-20261117/firearms/'+preset.cue+'.mp3']));
  for (const shot of recordings) {
    const id = preset.name+'-'+shot.name;
    const filter = [
      '[0:a]aresample=44100,asplit=3[a][b][c]',
      '[a]'+band(preset.attack)+',afade=t=out:st=0.055:d=0.13[a1]',
      '[b]'+band(preset.body)+',volume=0.35,afade=t=out:st=0.09:d=0.15[b1]',
      '[c]'+band(preset.tail)+',volume=0.26,afade=t=in:st=0.035:d=0.06,afade=t=out:st=0.24:d=0.17[c1]',
      '[1:a]aresample=44100,aformat=channel_layouts=mono,'+band([1600,6000])+',atrim=duration=0.062,afade=t=out:st=0.025:d=0.037,volume='+preset.latchGain+',adelay='+shot.latchDelay+',apad[m]',
      '[a1][b1][c1][m]amix=inputs=4:duration=first',
    ].join(';');
    const pcm = samples(['-ss',String(shot.start),'-t',String(duration),'-i',raw,'-i',latch,'-filter_complex',filter]);
    let lo=0,hi=100;
    for (let i=0;i<30;i++) {
      const gain=(hi+lo)/2;
      const level=attackRms(pcm.map(x=>preset.peak*Math.tanh(gain*x/preset.peak)));
      if (level<target) lo=gain; else hi=gain;
    }
    const gain=(lo+hi)/2;
    const mastered=pcm.map(x=>preset.peak*Math.tanh(gain*x/preset.peak));
    const file=publicDir+'/'+id+'.mp3';
    run(['-f','f32le','-ar',String(rate),'-ac','1','-i','pipe:0','-map_metadata','-1','-c:a','libmp3lame','-b:a','128k','-y',file],Buffer.from(mastered.buffer));
    files[id]={cue:preset.cue, sourceStartSeconds:shot.start, sourceDurationSeconds:duration, latchDelayMs:shot.latchDelay,
      path:'/'+file.slice('public/'.length), hash:'sha256-'+hash(file), bytes:readFileSync(file).length};
  }
}
const total=Object.values(files).reduce((sum,file)=>sum+file.bytes,0);
const info={creator:['Ben Jaszczak','Brian Nelson','Kevin Heras','Matthew Nanney','Kenney'],license:'CC0-1.0',
  commercialUse:true,modification:true,redistribution:true,
  producerApproval:'Issue 177 P03, existing recorded materials for distinct firearm sounds.',
  originalRecordings:[raw,latch].map(file=>({file,sha256:hash(file)})),
  notices:['assets/source/weapon-recordings/LICENSE.txt','assets/source/v100/audio/kenney-rpg/License.txt'],
  method:'Two different discharges from the same field recording. The suppressed pistol is a filtered game sound. Original timing and pitch; RMS matched to each existing first take over 200 ms.',
  recipe:'scripts/build-pistol-takes.mjs',runtimeAssetCount:4,logicalBytes:total,distinctBytes:total,files};
writeFileSync(sourceDir+'/provenance.json',JSON.stringify(info,null,2)+'\n');
const metadata=Object.fromEntries(Object.entries(files).map(([id,{path,hash}])=>[id,{path,hash}]));
writeFileSync('app/pwaPistolTakeFiles.js','// Generated by scripts/build-pistol-takes.mjs. Install metadata only.\nexport const PWA_PISTOL_TAKE_FILES = Object.freeze('+JSON.stringify(metadata,null,2)+');\n');
console.log(JSON.stringify({files:Object.keys(files),bytes:total}));
