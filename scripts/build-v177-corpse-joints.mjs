import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { V177_JOINT_ATLASES } from '../app/v177JointPresentation.js';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source='assets/source/v100/joints/corpse-collapse-r1.json';
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const transform=(m,[x,y])=>[m[0]*x+m[2]*y+m[4],m[1]*x+m[3]*y+m[5]];
function hull(points) {
  const cross=(o,a,b)=>(a[0]-o[0])*(b[1]-o[1])-(a[1]-o[1])*(b[0]-o[0]);
  const sorted=[...new Map(points.map(p=>[p.join(','),p])).values()].sort((a,b)=>a[0]-b[0]||a[1]-b[1]);
  const lower=[],upper=[];
  for(const p of sorted){while(lower.length>1&&cross(lower.at(-2),lower.at(-1),p)<=0)lower.pop();lower.push(p);}
  for(const p of sorted.toReversed()){while(upper.length>1&&cross(upper.at(-2),upper.at(-1),p)<=0)upper.pop();upper.push(p);}
  return lower.slice(0,-1).concat(upper.slice(0,-1));
}
function movedEffector(matrix,pivot,angle,dx,dy) {
  const [x,y]=transform(matrix,pivot),c=Math.cos(angle),s=Math.sin(angle);
  const result=[c*matrix[0]-s*matrix[1],s*matrix[0]+c*matrix[1],
    c*matrix[2]-s*matrix[3],s*matrix[2]+c*matrix[3],0,0];
  result[4]=x+dx-result[0]*pivot[0]-result[2]*pivot[1];
  result[5]=y+dy-result[1]*pivot[0]-result[3]*pivot[1];
  return result;
}

export async function buildV177CorpseJointData() {
  const bytes=fs.readFileSync(path.join(root,source)),recipes=JSON.parse(bytes),data={};
  assert.equal(recipes.schemaVersion,1);
  for(const [kind,recipe]of Object.entries(recipes.forms)) {
    const atlas=V177_JOINT_ATLASES[kind];assert.equal(atlas.type,'rigid-parts');assert.equal(atlas.path,recipe.atlasPath);
    const image=fs.readFileSync(path.join(root,'public',atlas.path));assert.equal(sha(image),recipe.atlasSha256);
    const {data:rgba,info}=await sharp(image).ensureAlpha().raw().toBuffer({resolveWithObject:true});
    const outlines=atlas.parts.map(part=>{
      const s=part.source,d=part.destination,points=[];
      for(let x=0;x<s.w;x++) {
        let top=s.h,bottom=-1;
        for(let y=0;y<s.h;y++)if(rgba[((s.y+y)*info.width+s.x+x)*4+3]>=8){top=Math.min(top,y);bottom=Math.max(bottom,y);}
        if(bottom>=0)for(const [px,py]of [[x,top],[x+1,top],[x,bottom+1],[x+1,bottom+1]])points.push([d.x+px*d.w/s.w,d.y+py*d.h/s.h]);
      }
      assert.ok(points.length,part.name+' must contain owned source paint');
      return {name:part.name,hull:hull(points)};
    });
    const falls={};
    for(const side of ['-1','1']) {
      falls[side]={};assert.ok(recipe.falls[side]?.length);
      for(const change of recipe.falls[side]) {
        const chain=[...(atlas.armConstraints??[]),...(atlas.legConstraints??[])].find(c=>c.effectorBone===change.bone);
        const attachment=atlas.parentAttachments?.[change.bone];
        assert.ok(chain||attachment,change.bone+' must be an authored effector or attached bone');
        assert.ok([change.dx,change.dy,change.angle].every(Number.isFinite));
        if(!chain){assert.equal(change.dx,0,'an attached bone must retain its original hinge');assert.equal(change.dy,0,'an attached bone must retain its original hinge');}
        const pivot=atlas.interpolationPivots[change.bone]??chain?.effectorWrist??chain?.ankle??chain?.wrist??attachment?.pivot;
        assert.ok(Array.isArray(pivot)&&pivot.length===2&&pivot.every(Number.isFinite));
        falls[side][change.bone]=movedEffector(atlas.poses[0][change.bone],pivot,change.angle,change.dx,change.dy);
      }
    }
    const names=new Set(atlas.parts.map(p=>p.name));
    for(const group of Object.values(recipe.severedParts))assert.ok(group.length&&group.every(name=>names.has(name)));
    data[kind]={atlasPath:atlas.path,atlasSha256:recipe.atlasSha256,atlasSize:{width:info.width,height:info.height},sourceSha256:sha(bytes),
      layoutSha256:sha(JSON.stringify({parts:atlas.parts,reference:atlas.referenceFrame,neutral:atlas.poses[0]})),
      alphaThreshold:8,outlines,falls,severedParts:recipe.severedParts};
  }
  return '// Generated by scripts/build-v177-corpse-joints.mjs; approved source RGBA is unchanged.\n'
    +'export const V177_CORPSE_JOINT_DATA = '+JSON.stringify(data)+';\n';
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const output=path.join(root,'app/v177CorpseJointData.js'),content=await buildV177CorpseJointData();
  if(process.argv.includes('--check'))assert.equal(fs.readFileSync(output,'utf8').replace(/\r\n/g,'\n'),content);
  else fs.writeFileSync(output,content);
  console.log(JSON.stringify({output:path.relative(root,output),forms:3,bytes:Buffer.byteLength(content),check:process.argv.includes('--check')}));
}
