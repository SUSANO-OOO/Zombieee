test("one-tap emergency evade locks the old ray and chooses a different far lane", () => {
  const target = human();
  const tracking = beginKuromeTracking(target).runtime;
  const planned = kuromeEmergencyEvadePlan({
    runtime: tracking,
    target,
    tap: { x: target.x + 18, y: target.y - 32 },
    laneCenters: [240, 285, 325],
  });
  assert.equal(planned.ok, true);
  assert.equal(planned.lane, 2);
  assert.equal(planned.runtime.phase, "locked");
  assert.equal(planned.runtime.targetX, target.x);
  assert.equal(planned.runtime.targetY, target.y);
  const nextTick = advanceKuromeTracking(
    planned.runtime,
    .05,
    human({ y: 325, lane: planned.lane }),
  );
  assert.equal(nextTick.runtime.phase, "locked");
  assert.equal(nextTick.runtime.targetY, target.y);
  const fired = advanceKuromeTracking(nextTick.runtime, 1);
  assert.deepEqual(resolveKuromeBeam({
    boss: { x: 760, y: 270 },
    runtime: fired.runtime,
    candidates: [human({ y: 325, lane: planned.lane })],
  }).hits, []);
  assert.equal(kuromeEmergencyEvadePlan({
    runtime: tracking,
    target,
    tap: { x: 900, y: 20 },
  }).ok, false);
});

test("invalid targets cannot start and the full state machine terminates", () => {
  assert.equal(beginKuromeTracking(human({ hp: 0 })).ok, false);
  let runtime = beginKuromeTracking(human()).runtime;
  let fired = 0;
  let recovered = 0;
  for (let index = 0; index < 20 && runtime.phase !== "idle"; index += 1) {
    const step = advanceKuromeTracking(runtime, .2, human());
    runtime = step.runtime;
    if (step.fired) fired += 1;
    if (step.recovered) recovered += 1;
  }
  assert.deepEqual(runtime, createKuromeTrackingRuntime());
  assert.equal(fired, 1);
  assert.equal(recovered, 1);
  assert.ok(KUROME_PROTOTYPE_TUNING.warningSeconds > KUROME_PROTOTYPE_TUNING.trackingSeconds);
});

test("prototype ledger fixes the exact generated bytes, dimensions, and builder provenance", async () => {
  const ledger = JSON.parse(await readFile(
    path.join(root, "docs/BOSS_PROTOTYPE_ASSETS_0.9.0.json"),
    "utf8",
  ));
  assert.equal(ledger.status, "producer-approved");
  assert.equal(ledger.generatedAssets.length, 3);
  const repairProof=JSON.parse(await readFile(path.join(root,"assets/source/v100/sprite-repairs/ground-matte-provenance.json"),"utf8"));
  const repair=repairProof.records.find(record=>record.kind==="kurome");
  for (const asset of ledger.generatedAssets) {
    const absolutePath = path.join(root, asset.path);
    const bytes = await readFile(absolutePath);
    const metadata = await sharp(bytes).metadata();
    if(asset.path==="public"+repair.path){
      const original=execFileSync("git",["show",repairProof.base+":"+asset.path],{cwd:root,maxBuffer:4*1024*1024});
      assert.equal(createHash("sha256").update(original).digest("hex"),asset.sha256,"retain the producer-approved original ledger");
      assert.equal(original.length,asset.bytes);
      assert.equal(asset.sha256,repair.previousPNG);
      assert.equal(createHash("sha256").update(bytes).digest("hex"),repair.pngSha256);
      assert.equal(bytes.length,repair.pngBytes);
      assert.equal(repair.sourceRepair.allSourceRGBRetained,true);
      assert.equal(repair.sourceRepair.alphaChanges,28230);
      assert.ok(repairProof.sourceGenerators.includes(asset.generatedBy));
    }else{
      assert.equal(createHash("sha256").update(bytes).digest("hex"), asset.sha256);
      assert.equal(bytes.length, asset.bytes);
    }
    assert.deepEqual([metadata.width, metadata.height], asset.dimensions);
    assert.equal(asset.generatedBy, "scripts/build-v090-kurome-prototype-assets.mjs");
    assert.ok(asset.derivedFrom.every((sourcePath) => ledger.sourceAssets.some(({ path: candidate }) => candidate === sourcePath)));
  }
});
