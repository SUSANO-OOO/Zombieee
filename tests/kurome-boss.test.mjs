const human = (overrides = {}) => ({
  id: 1,
  side: "human",
  hp: 100,
  combatReady: true,
  targetable: true,
  x: 320,
  y: 270,
  lane: 1,
  bodyRadius: 11,
  ...overrides,
});

test("tracking follows during the readable window, then locks deterministically", () => {
  const started = beginKuromeTracking(human());
  assert.equal(started.ok, true);
  const following = advanceKuromeTracking(started.runtime, .3, human({ x: 350, y: 230, lane: 0 }));
  assert.equal(following.runtime.phase, "tracking");
  assert.equal(following.runtime.targetX, 350);
  assert.equal(following.runtime.targetY, 230);
  const locked = advanceKuromeTracking(following.runtime, .6, human({ x: 400, y: 330, lane: 2 }));
  assert.equal(locked.runtime.phase, "locked");
  assert.equal(locked.runtime.targetX, 350);
  assert.equal(locked.runtime.targetY, 230);
  const fired = advanceKuromeTracking(locked.runtime, 1);
  assert.equal(fired.fired, true);
  assert.equal(fired.runtime.phase, "firing");
});

test("beam hits a held target and misses a target that leaves the locked ray", () => {
  const boss = { x: 760, y: 270 };
  const firing = { phase: "firing", targetX: 320, targetY: 270 };
  assert.deepEqual(
    resolveKuromeBeam({ boss, runtime: firing, candidates: [human()] }).hits,
    ["1"],
  );
  assert.deepEqual(
    resolveKuromeBeam({
      boss,
      runtime: firing,
      candidates: [human({ y: 365, lane: 2 })],
    }).hits,
    [],
  );
});

